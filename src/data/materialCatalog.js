// ---------- Lógica de emparejamiento y consolidado ----------

function normalize(s) {
  return (s || "").toUpperCase().trim().replace(/\s+/g, " ")
    .replace(/Á/g,"A").replace(/É/g,"E").replace(/Í/g,"I").replace(/Ó/g,"O").replace(/Ú/g,"U");
}

// Busca el medicamento en el catálogo de material por defecto. Los nombres en
// las sesiones se capturan como texto libre (no de un catálogo fijo), así que
// se intenta primero coincidencia exacta y luego que el nombre contenga o esté
// contenido en alguna de las claves conocidas.
export function matchMedication(medName, extraDefaults = {}) {
  const allDefaults = { ...MATERIAL_DEFAULTS, ...extraDefaults };
  const norm = normalize(medName);
  if (!norm) return null;
  if (allDefaults[norm]) return norm;
  const keys = Object.keys(allDefaults);
  return keys.find(k => norm.includes(k) || k.includes(norm)) || null;
}

// Extrae volumen y tipo (SF/SG) de un texto de dilución libre, ej. "250 ML SF" o "100 ML SG5%"
function parseDiluent(diluent) {
  if (!diluent) return null;
  const volMatch = diluent.match(/(\d+)\s*ML/i);
  const vol = volMatch ? parseInt(volMatch[1]) : null;
  const isSG = /SG/i.test(diluent);
  const isSF = /SF/i.test(diluent);
  if (!vol || (!isSG && !isSF)) return null;
  return { vol, type: isSG ? "SG" : "SF" };
}

// Busca en el catálogo maestro la presentación de solución que coincide con el
// volumen y tipo detectados en la dilución real capturada en la sesión.
function solutionItemFor(vol, type) {
  const wanted = type === "SG" ? "GLUCOSA 5%" : "CLORURO DE SODIO 0.9%";
  const re = new RegExp(`${wanted}\\s+${vol}\\s*ML\\b`, "i");
  return MASTER_CATALOG.find(c => re.test(c.item));
}

// Extrae el contenido en mg de una presentación del catálogo, ej.
// "CARBOPLATINO 150 MG/ 15 ML SOL. INY." -> 150 ; "GEMCITABINA 1 GR. SOL. INY." -> 1000
function parsePresentationMg(itemName) {
  const gr = itemName.match(/(\d+(?:\.\d+)?)\s*GR\.?/i);
  if (gr) return parseFloat(gr[1]) * 1000;
  const mg = itemName.match(/(\d+(?:\.\d+)?)\s*MG/i);
  if (mg) return parseFloat(mg[1]);
  const mcg = itemName.match(/(\d+(?:\.\d+)?)\s*MCG/i);
  if (mcg) return parseFloat(mcg[1]) / 1000;
  return null;
}

// Extrae el valor numérico en mg de la dosis prescrita, ej. "150 MG" -> 150, "1 GR" -> 1000
function parseDoseMg(doseStr) {
  if (!doseStr) return null;
  const gr = doseStr.match(/(\d+(?:\.\d+)?)\s*GR/i);
  if (gr) return parseFloat(gr[1]) * 1000;
  const mg = doseStr.match(/(\d+(?:\.\d+)?)/);
  return mg ? parseFloat(mg[1]) : null;
}

// Calcula cuántas piezas/frascos de cada presentación disponible se necesitan
// para cubrir la dosis prescrita de un medicamento (usa las presentaciones más
// grandes primero para minimizar el número de piezas abiertas).
// Devuelve { doseMg, pieces: [{item, mg, count}], totalMg, waste } o null si no se pudo calcular.
export function computeMedicationPieces(medName, doseStr, extraCatalog = [], extraDefaults = {}) {
  const doseMg = parseDoseMg(doseStr);
  if (!doseMg) return null;

  const norm = normalize(medName);
  const key = matchMedication(medName, extraDefaults);
  const searchTerm = key || norm.split(" ")[0];
  const allCatalog = [...MASTER_CATALOG, ...extraCatalog];
  const candidates = allCatalog
    .filter(c => ["Oncológicos", "Inmunoterapia", "Medicamentos"].includes(c.category))
    .map(c => ({ item: c.item, mg: parsePresentationMg(c.item) }))
    .filter(c => c.mg && normalize(c.item).startsWith(searchTerm));

  if (candidates.length === 0) return null;

  // Deduplicar por mg (si hay presentaciones repetidas con el mismo contenido)
  const uniqueByMg = [];
  const seenMg = new Set();
  candidates.forEach(c => { if (!seenMg.has(c.mg)) { seenMg.add(c.mg); uniqueByMg.push(c); } });
  uniqueByMg.sort((a,b) => b.mg - a.mg); // más grande primero

  let remaining = doseMg;
  const pieces = [];
  uniqueByMg.forEach(c => {
    if (remaining <= 0) return;
    const count = Math.floor(remaining / c.mg);
    if (count > 0) { pieces.push({ item: c.item, mg: c.mg, count }); remaining -= count * c.mg; }
  });
  // Lo que sobre (menor a la presentación más chica disponible) se cubre con una pieza más de la más chica
  if (remaining > 0.01) {
    const smallest = uniqueByMg[uniqueByMg.length - 1];
    const existing = pieces.find(p => p.item === smallest.item);
    if (existing) existing.count += 1; else pieces.push({ item: smallest.item, mg: smallest.mg, count: 1 });
    remaining -= smallest.mg;
  }

  const totalMg = pieces.reduce((acc, p) => acc + p.mg * p.count, 0);
  return { doseMg, pieces, totalMg, waste: totalMg - doseMg };
}
// de punción según el tipo de acceso usado (session.catheterType: "periferico" | "puerto")
// y el calibre elegido (session.catheterGauge, cuando el tipo tiene alternativas).
// Las soluciones (cloruro/glucosa) se calculan según la dilución REAL capturada
// en cada medicamento cuando es posible — lo del catálogo son solo probables.
// Devuelve { items: [{item, qty}], unmatched: [...], pendingAlternatives: [...] }
export function computeSessionMaterial(session, overrides = {}) {
  const { extraDefaults = {}, extraCatalog = [], puncionOverrides = {}, patientDefaultMaterial = null } = overrides;
  const allDefaults = { ...MATERIAL_DEFAULTS, ...extraDefaults };
  const allPuncion = { ...PUNCION_DEFAULTS, ...puncionOverrides };
  const allCatalog = [...MASTER_CATALOG, ...extraCatalog];
  const combined = {};
  const unmatched = [];
  const add = (item, qty) => { combined[item] = (combined[item] || 0) + qty; };

  const findSolution = (vol, type) => {
    const wanted = type === "SG" ? "GLUCOSA 5%" : "CLORURO DE SODIO 0.9%";
    const re = new RegExp(`${wanted}\\s+${vol}\\s*ML\\b`, "i");
    return allCatalog.find(c => re.test(c.item));
  };

  // Material base del paciente: aplica a (casi) todas las sesiones por defecto,
  // salvo que se excluya explícitamente para esa sesión en particular.
  if (patientDefaultMaterial && !session.excludePatientDefault) {
    (patientDefaultMaterial.insumos || []).forEach(({ item, qty }) => add(item, qty));
    (patientDefaultMaterial.soluciones || []).forEach(({ item, qty }) => add(item, qty));
  }

  (session.meds || []).forEach(m => {
    if (!m.name) return;
    const norm = normalize(m.name);
    const key = allDefaults[norm] ? norm : Object.keys(allDefaults).find(k => norm.includes(k) || k.includes(norm));
    if (!key) { unmatched.push(m.name); return; }
    const entry = allDefaults[key];
    entry.insumos.forEach(({ item, qty }) => add(item, qty));

    const parsed = parseDiluent(m.diluent);
    const solItem = parsed && findSolution(parsed.vol, parsed.type);
    if (solItem) {
      add(solItem.item, 1);
    } else {
      entry.soluciones.forEach(({ item, qty }) => add(item, qty));
    }
  });

  const pendingAlternatives = [];
  if (session.catheterType && allPuncion[session.catheterType]) {
    const p = allPuncion[session.catheterType];
    p.insumos.forEach(({ item, qty }) => add(item, qty));
    p.soluciones.forEach(({ item, qty }) => add(item, qty));
    (p.alternativas || []).forEach(alt => {
      const chosen = alt.options.find(o => o.item === session.catheterGauge);
      if (chosen) add(chosen.item, chosen.qty);
      else pendingAlternatives.push(alt);
    });
  }

  return {
    items: Object.entries(combined).map(([item, qty]) => ({ item, qty })).sort((a,b) => a.item.localeCompare(b.item)),
    unmatched,
    pendingAlternatives,
  };
}
