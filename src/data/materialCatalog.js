export function computeSessionMaterial(session, overrides = {}) {
  const { extraDefaults = {}, extraCatalog = [], puncionOverrides = {}, patientDefaultMaterial } = overrides;
  const allDefaults = { ...MATERIAL_DEFAULTS, ...extraDefaults };
  const allPuncion = { ...PUNCION_DEFAULTS, ...puncionOverrides };
  const allCatalog = [...MASTER_CATALOG, ...extraCatalog];
  const effectivePatientDefault = patientDefaultMaterial || PATIENT_DEFAULT_MATERIAL;

  const combined = {};
  const unmatched = [];
  const unmatchedSolutions = [];

  const add = (item, qty) => {
    const cleanItem = String(item).trim().replace(/\s+/g, " ");
    combined[cleanItem] = (combined[cleanItem] || 0) + qty;
  };

  if (effectivePatientDefault && !session.excludePatientDefault) {
    (effectivePatientDefault.insumos || []).forEach(({ item, qty }) => add(item, qty));
    (effectivePatientDefault.soluciones || []).forEach(({ item, qty }) => add(item, qty));
  }

const PREMEDICACION_DRUGS = new Set([
  "FOSAPREPITANT", "PALONOSETRON", "DEXAMETASONA", "ONDANSETRON", "DIFENHIDRAMINA",
  "HIDROCORTISONA", "ACIDO ZOLEDRONICO", "CARBOXIMALTOSA", "FUROSEMIDA", "HIOSCINA",
  "KETOROLACO", "MESNA", "METILPREDNISOLONA", "METOCLOPRAMIDA", "OMEPRAZOL",
  "TRAMADOL", "CLOROPIRAMINA",
]);

  (session.meds || []).forEach(m => {
    if (!m.name) return;
    const norm = normalize(m.name);
    const key = allDefaults[norm] ? norm : Object.keys(allDefaults).find(k => norm.includes(k) || k.includes(norm));
    if (!key) { unmatched.push(m.name); return; }

    // Si el medicamento es de vía ORAL (según su dosis, cuando el nombre es
    // ambiguo), no se le asigna material de inyección ni solución.
    const route = routeFor(m.name, m.dose, extraDefaults);
    if (route === "ORAL") return;

    const entry = allDefaults[key];
    entry.insumos.forEach(({ item, qty }) => add(item, qty));

    // Premedicación: no se calcula solución (van directo en bolo/IV corto),
    // excepto Fosaprepitant, que siempre lleva Cloruro de Sodio 100 ML fijo.
    if (PREMEDICACION_DRUGS.has(key)) {
      if (key === "FOSAPREPITANT") add("CLORURO DE SODIO 0.9% 100 ML", 1);
      return;
    }

    const parsed = parseDiluent(m.diluent);
    const solItem = parsed && solutionItemFor(parsed.vol, parsed.type, allCatalog);
    if (solItem) {
      add(solItem.item, 1);
    } else if (entry.soluciones.length > 0) {
      entry.soluciones.forEach(({ item, qty }) => add(item, qty));
    } else {
      unmatchedSolutions.push({ name: m.name, diluent: m.diluent || "(sin dilución capturada)" });
    }
  });

  const pendingAlternatives = [];
  if (session.catheterType && allPuncion[session.catheterType]) {
    const p = allPuncion[session.catheterType];
    p.insumos.forEach(({ item, qty }) => add(item, qty));
    p.soluciones.forEach(({ item, qty }) => add(item, qty));
    (p.alternativas || []).forEach(alt => {
      const chosen = alt.options.find(o => o.item === session.catheterGauge);
      if (chosen) add(chosen.item, chosen.qty);
      else pendingAlternatives.push(alt);
    });
  }

  let pendingEquipo = false;
  if (!session.equipoChoice) {
    pendingEquipo = true;
  } else if (session.equipoChoice !== "ninguno") {
    add(EQUIPO_OPTIONS[session.equipoChoice], 1);
  }

  // Aplicar los ajustes guardados desde el modal de solicitud (solo afecta
  // insumos/soluciones, nunca al medicamento en sí -- eso se agrega después,
  // ver nota abajo): artículos excluidos, cantidades editadas a mano, y
  // material extra anexado.
  (session.excludedMaterial || []).forEach(item => { delete combined[item]; });
  Object.entries(session.qtyOverrides || {}).forEach(([item, qty]) => {
    if (combined[item] !== undefined) combined[item] = qty;
  });
  (session.extraMaterial || []).forEach(({ item, qty }) => add(item, qty || 0));

  // Piezas del medicamento en sí (frascos/ampolletas según la dosis) -- se
  // agrega AL FINAL a propósito: su cantidad correcta solo la define
  // pieceOverrides (o el cálculo automático), nunca qtyOverrides -- si el
  // nombre de la presentación coincidiera por casualidad con algo ya en la
  // lista de insumos, esto asegura que el medicamento tenga la última
  // palabra y no quede pisado por un ajuste de insumos.
  (session.meds || []).forEach((m, idx) => {
    if (!m.name || !m.dose) return;
    const medKey = `${idx}_${m.name}`;
    const overridden = session.pieceOverrides?.[medKey];
    if (overridden) {
      overridden.forEach(({ item, count }) => {
        if (count > 0) combined[item] = count;
        else delete combined[item];
      });
    } else {
      const auto = computeMedicationPieces(m.name, m.dose, extraCatalog, extraDefaults);
      if (auto) auto.pieces.forEach(({ item, count }) => { if (count > 0) combined[item] = count; });
    }
  });

  return {
    items: Object.entries(combined).filter(([, qty]) => qty !== undefined).map(([item, qty]) => ({ item, qty })).sort((a,b) => a.item.localeCompare(b.item)),
    unmatched,
    unmatchedSolutions,
    pendingAlternatives,
    pendingEquipo,
  };
}
